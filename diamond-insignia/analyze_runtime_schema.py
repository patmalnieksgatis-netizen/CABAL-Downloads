#!/usr/bin/env python3
"""Interpret existing CABAL Diamond read-only SQL metadata audit.

Input is the JSON generated by Audit-DiamondRuntime-v291.ps1. Does not connect
or write to any database. Does not inspect player/character rows or credentials.
"""
import collections
import json
import pathlib
import re
import sys

TOPICS = re.compile(r'(?i)merit|mastery|diamond|insignia|medal')
KEY_LIKE = re.compile(r'(?i)(?:^|_)(?:char(?:acter)?|user|account|player|idx|id|guid|grade|point|score|level|rank)(?:_|$)|(?:Index|Idx|ID|Grade|Point|Score|Level|Rank)$')


def analyze(doc: dict) -> dict:
    if doc.get('mode') != 'READ_ONLY' or doc.get('sql_mutations') is not False:
        raise ValueError('Unexpected unsafe or missing audit markers')
    db = doc.get('database') or {}
    rows = db.get('columns') or []
    groups = collections.defaultdict(list)
    for c in rows:
        if not all(k in c for k in ('schema', 'table', 'column', 'data_type')):
            raise ValueError('Malformed column metadata')
        groups[(c['schema'], c['table'])].append((c['column'], c['data_type']))
    tables = []
    for (schema, table), cols in sorted(groups.items()):
        relevant = [(name, ty) for name, ty in cols if TOPICS.search(name)]
        tables.append({
            'schema': schema,
            'table': table,
            'returned_column_count': len(cols),
            'matching_column_names': [name for name, _ in relevant],
            'potential_key_columns_NOT_CONFIRMED': [name for name, _ in cols if KEY_LIKE.search(name)],
            'columns': [{'name': name, 'type': ty} for name, ty in cols],
        })
    game = doc.get('game') or {}
    return {
        'mode': 'OFFLINE_READ_ONLY',
        'source_status': db.get('status'),
        'original_total_matching_columns': db.get('row_count'),
        'returned_rows': len(rows),
        'sql_query_limit': db.get('limited_to_first'),
        'could_be_truncated': db.get('limited_to_first') is not None and len(rows) >= db['limited_to_first'],
        'table_count': len(tables),
        'tables': tables,
        'live_world_inner_pid': game.get('world_inner_pid'),
        'loaded_game_modules': [{'name': m.get('name'), 'sha256': m.get('sha256'),
                                'diamond_literal': m.get('has_diamond_literal')}
                                for m in (game.get('game_modules') or [])],
        'client_packets_examined': False,
        'sql_foreign_keys_examined': False,
        'sql_column_constraints_examined': False,
        'database_values_read': False,
        'diamond_persistence_proven': False,
        'next_steps': 'Audit actual PK/FK/index definitions and specific Merit packet handlers before designing an additive schema.'
    }


def main():
    if len(sys.argv) != 2:
        raise SystemExit('Usage: python analyze_runtime_schema.py CABAL_DIAMOND_RUNTIME_AUDIT.json')
    d = json.loads(pathlib.Path(sys.argv[1]).read_text(encoding='utf-8-sig'))
    out = analyze(d)
    print(json.dumps(out, indent=2, ensure_ascii=False))


if __name__ == '__main__':
    main()
